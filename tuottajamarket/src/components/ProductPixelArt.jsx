function resolveSpriteKey(title = "", category = "") {
	const haystack = `${title} ${category}`.toLocaleLowerCase("fi");
	for (const [spriteKey, keywords] of KEYWORD_RULES) {
		if (keywords.some((word) => haystack.includes(word))) {
			return spriteKey;
		}
	}
	return "crate";
}

export function ProductPixelArt({ title, category, size = 72, className = "" }) {
	const spriteKey = resolveSpriteKey(title, category);
	const sprite = SPRITES[spriteKey];

	return (
		<div
			className={`pixel-art-frame ${className}`.trim()}
			style={{ backgroundColor: sprite.bg }}
			aria-hidden="true"
		>
			<svg
				width={size}
				height={size}
				viewBox="0 0 16 16"
				shapeRendering="crispEdges"
				className="pixel-art-svg"
			>
				{sprite.grid.map((row, y) =>
					[...row].map((cell, x) => {
						const color = sprite.palette[cell];
						if (!color) return null;
						return <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={color} />;
					})
				)}
			</svg>
		</div>
	);
}
